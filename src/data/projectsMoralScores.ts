export function getProjectProvince(proj: {
  id?: number;
  province?: string;
  organization?: string;
  projectName?: string;
  details?: { context?: string };
}): string {
  if (proj.province && proj.province.trim()) {
    return proj.province.trim();
  }
  const org = (proj.organization || '').trim();
  if (org && LEARNING_CENTER_PROVINCE_BY_ORG[org]) {
    return LEARNING_CENTER_PROVINCE_BY_ORG[org];
  }
  const searchText = `${org} ${proj.projectName || ''} ${proj.details?.context || ''}`;
  for (const prov of THAI_PROVINCES) {
    if (searchText.includes(prov)) {
      return prov;
    }
  }
  if (searchText.includes('กทม')) return 'กรุงเทพมหานคร';
  return 'กรุงเทพมหานคร';
}


