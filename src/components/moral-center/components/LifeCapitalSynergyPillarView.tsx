// Helper to get pillar metadata
export function getLifeCapitalPillarMeta(key: string): PillarMeta {
  return PILLAR_CONFIGS[key] || PILLAR_CONFIGS.family;
}

export function getAllLifeCapitalSynergyTopics() {
  const allPillars = ['family', 'talent', 'friend', 'community', 'identity'];
  return allPillars.flatMap(pillarKey => {
    const meta = PILLAR_CONFIGS[pillarKey];
    if (!meta) return [];
    return meta.topics.map(t => ({
      ...t,
      dimensionKey: meta.key,
      dimensionName: meta.name,
      dimensionColor: meta.accentColor
    }));
  });
}

