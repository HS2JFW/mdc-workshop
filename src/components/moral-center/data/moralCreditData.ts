export const MORAL_CREDIT_MEMBERS: MoralCreditMemberSummary[] = (() => {
  const map = new Map<number, MoralCreditMemberSummary>();

  for (const row of MORAL_CREDIT_RAW_ROWS) {
    let mem = map.get(row.memberId);
    if (!mem) {
      mem = {
        memberId: row.memberId,
        fullName: row.fullName,
        agency: row.agency,
        agencyShort: getShortAgencyName(row.agency),
        district: row.district,
        province: row.province,
        tier: row.tier,
        totalScore: row.memberTotalScore,
        totalFrequency: 0,
        deedTypesCount: 0,
        activeDimensionsCount: 0,
        scoreBracketKey: 'inactive',
        scoreBracketLabel: '0 คะแนน (Inactive)',
        isActive: row.memberTotalScore > 0,
        archetype: 'Inactive (0 คะแนน)',
        categoryScores: {
          จิตอาสา: 0,
          วินัย: 0,
          พอเพียง: 0,
          กตัญญู: 0,
          สุจริต: 0,
          อื่นๆ: 0
        },
        categoryCounts: {
          จิตอาสา: 0,
          วินัย: 0,
          พอเพียง: 0,
          กตัญญู: 0,
          สุจริต: 0,
          อื่นๆ: 0
        },
        deeds: []
      };
      map.set(row.memberId, mem);
    }

    if (row.points > 0 || row.frequency > 0) {
      mem.totalFrequency += row.frequency;
      mem.deedTypesCount += 1;
      if (row.category) {
        mem.categoryScores[row.category] += row.points;
        mem.categoryCounts[row.category] += row.frequency;
      }
      mem.deeds.push({
        deedTitle: row.deedTitle,
        category: row.category || 'อื่นๆ',
        frequency: row.frequency,
        points: row.points
      });
    }
  }

  const list = Array.from(map.values()).sort((a, b) => a.memberId - b.memberId);
  for (const m of list) {
    m.activeDimensionsCount = ALL_CATEGORIES.filter((cat) => m.categoryScores[cat] > 0).length;

    if (!m.isActive || m.totalScore === 0) {
      m.scoreBracketKey = 'inactive';
      m.scoreBracketLabel = '0 คะแนน (Inactive)';
      m.archetype = 'Inactive (0 คะแนน)';
    } else if (m.totalScore <= 10) {
      m.scoreBracketKey = 'starter';
      m.scoreBracketLabel = '1–10 คะแนน (Starter)';
      m.archetype = m.totalFrequency >= 6 ? 'Routine Practitioner' : 'Emerging Contributor';
    } else if (m.totalScore <= 30) {
      m.scoreBracketKey = 'regular';
      m.scoreBracketLabel = '11–30 คะแนน (Regular)';
      m.archetype = m.totalFrequency >= 6 ? 'Routine Practitioner' : 'Emerging Contributor';
    } else if (m.totalScore <= 100) {
      m.scoreBracketKey = 'active';
      m.scoreBracketLabel = '31–100 คะแนน (Active)';
      m.archetype = m.totalFrequency >= 6 ? 'Routine Practitioner' : 'High-Impact Altruist';
    } else {
      m.scoreBracketKey = 'champion';
      m.scoreBracketLabel = '>100 คะแนน (Champion)';
      m.archetype = m.totalFrequency >= 15 ? 'Moral Champion' : 'High-Impact Altruist';
    }
  }

  return list;
})();

// System-wide KPI Overview
export const MORAL_CREDIT_KPI_OVERVIEW = (() => {
  const totalMembers = MORAL_CREDIT_MEMBERS.length;
  const activeMembers = MORAL_CREDIT_MEMBERS.filter((m) => m.isActive).length;
  const inactiveMembers = totalMembers - activeMembers;
  const activationRatePct = Number(((activeMembers / totalMembers) * 100).toFixed(2));

  const activeRows = MORAL_CREDIT_RAW_ROWS.filter((r) => r.points > 0 || r.frequency > 0);
  const totalTransactions = activeRows.length;
  const totalFrequency = activeRows.reduce((acc, r) => acc + r.frequency, 0);
  const totalPoints = activeRows.reduce((acc, r) => acc + r.points, 0);
  const avgPointsPerActiveMember = Number((totalPoints / Math.max(1, activeMembers)).toFixed(2));
  const avgPointsPerAction = Number((totalPoints / Math.max(1, totalFrequency)).toFixed(2));
  const avgTransactionsPerActive = Number((totalTransactions / Math.max(1, activeMembers)).toFixed(2));
  const avgFrequencyPerActive = Number((totalFrequency / Math.max(1, activeMembers)).toFixed(2));

  const uniqueDeedTypesCount = new Set(activeRows.map((r) => r.deedTitle).filter(Boolean)).size;

  const provList = MORAL_CREDIT_MEMBERS.map((m) => m.province).filter((p) => p !== 'ไม่ระบุจังหวัด');
  const uniqueProvinces = new Set(provList).size;

  const uniqueAgencies = new Set(
    MORAL_CREDIT_MEMBERS.map((m) => m.agencyShort).filter((a) => a !== 'ไม่ระบุหน่วยงาน')
  ).size;

  const tiersCount = {
    mdcMember: MORAL_CREDIT_MEMBERS.filter((m) => m.tier === 'MDC Member').length,
    platinum: MORAL_CREDIT_MEMBERS.filter((m) => m.tier === 'Platinum').length,
    gold: MORAL_CREDIT_MEMBERS.filter((m) => m.tier === 'Gold').length
  };

  const tiersPoints = {
    mdcMember: MORAL_CREDIT_MEMBERS.filter((m) => m.tier === 'MDC Member').reduce((a, b) => a + b.totalScore, 0),
    platinum: MORAL_CREDIT_MEMBERS.filter((m) => m.tier === 'Platinum').reduce((a, b) => a + b.totalScore, 0),
    gold: MORAL_CREDIT_MEMBERS.filter((m) => m.tier === 'Gold').reduce((a, b) => a + b.totalScore, 0)
  };

  return {
    totalMembers,
    activeMembers,
    inactiveMembers,
    activationRatePct,
    totalTransactions,
    totalRows: MORAL_CREDIT_RAW_ROWS.length,
    totalFrequency,
    totalPoints,
    avgPointsPerActiveMember,
    avgPointsPerAction,
    avgTransactionsPerActive,
    avgFrequencyPerActive,
    uniqueDeedTypesCount,
    uniqueProvinces,
    uniqueAgencies,
    tiersCount,
    tiersPoints
  };
})();

