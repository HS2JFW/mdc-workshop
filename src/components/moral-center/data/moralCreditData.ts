export function getShortAgencyName(agency: string): string {
  const clean = agency.trim();
  if (!clean) return 'ไม่ระบุหน่วยงาน';
  if (clean.includes('สำนักเลขาธิการนายกรัฐมนตรี')) return 'สลน. (สำนักเลขาธิการนายกฯ)';
  if (clean.includes('ศูนย์เทคโนโลยีสารสนเทศและการสื่อสาร')) return 'ศทส. สป.ดศ. (กระทรวงดิจิทัลฯ)';
  if (clean.includes('ศูนย์ปฏิบัติการต่อต้านการทุจริต')) return 'ศปท. สป.ดศ. (ต้านทุจริตดิจิทัลฯ)';
  if (clean.includes('ศูนย์คุณธรรม')) return 'ศคธ. (ศูนย์คุณธรรม)';
  if (clean.includes('กรมพัฒนาสังคมและสวัสดิการ')) return 'พส. (กรมพัฒนาสังคมฯ พม.)';
  if (clean.includes('วิทยาลัยพยาบาลบรมราชชนนี อุตรดิตถ์')) return 'วพบ.อุตรดิตถ์';
  if (clean.includes('กรมกิจการเด็กและเยาวชน')) return 'ดย. (กรมกิจการเด็กและเยาวชน)';
  if (clean.includes('กระทรวงแรงงาน')) return 'กระทรวงแรงงาน';
  if (clean.includes('clicknext')) return 'ClickNext Test';
  return clean;
}

