export const calculateMcaScore = (s: McaDimensionScores): number => {
  const sum = (s.inte * 30 + s.suff * 20 + s.disc * 15 + s.volu * 15 + s.grat * 20) / 100;
  return Number(sum.toFixed(2));
};

