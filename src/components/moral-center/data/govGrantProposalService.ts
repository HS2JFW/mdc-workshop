/**
 * บังคับให้บรรทัดชื่อโครงการภาษาไทยในหัวข้อที่ 1 ใช้ชื่อจากส่วนที่ 2 แบบตรงตัวทุกคำ
 */
function enforceLockedProjectTitle(content: string, lockedTitle: string): string {
  const cleanLocked = (lockedTitle || '').trim();
  if (!cleanLocked) return content;

  const lines = content.split(/\r?\n/);
  let inTitleSection = false;
  let replacedThaiLine = false;

  for (let i = 0; i < lines.length; i++) {
    const t = lines[i].trim();
    if (/^(?:\*\*)?1\.\s*ชื่อโครงการ/.test(t)) {
      inTitleSection = true;
      continue;
    }
    if (inTitleSection && /^(?:\*\*)?2\.\s+/.test(t)) {
      break;
    }
    if (inTitleSection) {
      if (/^[-•*]?\s*(?:\*\*)?ภาษาไทย(?:\*\*)?\s*[:：]/.test(t) || /^[-•*]?\s*(?:\*\*)?ชื่อโครงการภาษาไทย(?:\*\*)?\s*[:：]/.test(t)) {
        lines[i] = `- ภาษาไทย: ${cleanLocked}`;
        replacedThaiLine = true;
        break;
      }
      // กรณี AI ใส่ชื่อโครงการภาษาไทยต่อหลัง 1. ชื่อโครงการ โดยไม่มีคำว่า "ภาษาไทย:"
      if (!replacedThaiLine && t.length > 0 && !/ภาษาอังกฤษ|English/i.test(t) && !/^[-•*]/.test(t)) {
        lines[i] = `- ภาษาไทย: ${cleanLocked}`;
        replacedThaiLine = true;
        break;
      }
    }
  }

  return lines.join('\n');
}

